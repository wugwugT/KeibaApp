/**
 * JRA開催カレンダーからレース日付を逆引きする
 *
 * @param place - 競馬場名（例: "東京"）
 * @param year - QRコードの2桁年（例: 25）
 * @param round - 回（例: 3）
 * @param day - 日目（例: 5）
 * @returns "YYYY-MM-DD" 形式の日付文字列、該当なしの場合は null
 */
export function lookupRaceDate(
  place: string | null,
  year: number | null,
  round: number | null,
  day: number | null,
): string | null {
  if (!place || year === null || round === null || day === null) return null;
  const fullYear = String(2000 + year);
  return JRA_RACE_CALENDAR[place]?.[fullYear]?.[String(round)]?.[String(day)] ?? null;
}
